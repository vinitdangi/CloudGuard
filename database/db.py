"""Database connection and schema management for SQLite and PostgreSQL."""

import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator


def database_path() -> Path:
    """Return the configured local SQLite path or its development default."""
    configured_path = os.getenv("CLOUDGUARD_AUTH_DB")
    if configured_path:
        return Path(configured_path).expanduser().resolve()
    return Path(__file__).resolve().parents[1] / "data" / "cloudguard_users.sqlite3"


def _database_url() -> str | None:
    url = os.getenv("DATABASE_URL", "").strip()
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    return url or None


def _postgresql_requested() -> bool:
    return _database_url() is not None


def integrity_error_types() -> tuple[type[BaseException], ...]:
    """Return integrity-constraint errors supported by configured drivers."""
    errors: tuple[type[BaseException], ...] = (sqlite3.IntegrityError,)
    if _postgresql_requested():
        try:
            import psycopg
        except ImportError as exc:  # pragma: no cover - deployment configuration
            raise RuntimeError("PostgreSQL support requires the psycopg dependency.") from exc
        errors += (psycopg.IntegrityError,)
    return errors


class _PostgreSQLConnection:
    """Keep the repository's SQLite-style qmark SQL portable to psycopg."""

    def __init__(self, connection: Any):
        self._connection = connection

    def execute(self, query: str, parameters: tuple[Any, ...] = ()):
        return self._connection.execute(query.replace("?", "%s"), parameters)

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()


@contextmanager
def get_connection() -> Iterator[Any]:
    """Open the configured database, preferring DATABASE_URL when provided."""
    database_url = _database_url()
    if database_url:
        if not database_url.startswith("postgresql://"):
            raise RuntimeError("DATABASE_URL must use the PostgreSQL URL scheme.")
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:  # pragma: no cover - covered in deployment env
            raise RuntimeError("PostgreSQL support requires the psycopg dependency.") from exc
        connection = _PostgreSQLConnection(
            psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10)
        )
    else:
        if os.getenv("RAILWAY_ENVIRONMENT") or os.getenv("RAILWAY_PROJECT_ID"):
            raise RuntimeError("DATABASE_URL is required when running on Railway.")
        path = database_path()
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        try:
            path.parent.chmod(0o700)
        except OSError:
            pass
        connection = sqlite3.connect(path, timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")

    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def initialize_database() -> None:
    """Create account and scan-history tables without overwriting stored data."""
    if _postgresql_requested():
        user_table = """CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL,
            email TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            email_verified BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
        )"""
        history_table = """CREATE TABLE IF NOT EXISTS scan_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL,
            scan_timestamp TEXT NOT NULL,
            aws_account_id TEXT NOT NULL,
            aws_region TEXT NOT NULL,
            security_score DOUBLE PRECISION NOT NULL,
            total_findings INTEGER NOT NULL,
            critical_count INTEGER NOT NULL,
            high_count INTEGER NOT NULL,
            medium_count INTEGER NOT NULL,
            low_count INTEGER NOT NULL,
            passed_count INTEGER NOT NULL
        )"""
        results_table = """CREATE TABLE IF NOT EXISTS scan_results (
            scan_history_id BIGINT PRIMARY KEY,
            scan_result_json TEXT NOT NULL,
            FOREIGN KEY (scan_history_id) REFERENCES scan_history(id) ON DELETE CASCADE
        )"""
    else:
        user_table = """CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL COLLATE NOCASE UNIQUE,
            email TEXT NOT NULL COLLATE NOCASE UNIQUE,
            password_hash TEXT NOT NULL,
            email_verified INTEGER NOT NULL DEFAULT 1,
            created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
        )"""
        history_table = """CREATE TABLE IF NOT EXISTS scan_history (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL,
            scan_timestamp TEXT NOT NULL,
            aws_account_id TEXT NOT NULL,
            aws_region TEXT NOT NULL,
            security_score REAL NOT NULL,
            total_findings INTEGER NOT NULL,
            critical_count INTEGER NOT NULL,
            high_count INTEGER NOT NULL,
            medium_count INTEGER NOT NULL,
            low_count INTEGER NOT NULL,
            passed_count INTEGER NOT NULL
        )"""
        results_table = """CREATE TABLE IF NOT EXISTS scan_results (
            scan_history_id INTEGER PRIMARY KEY,
            scan_result_json TEXT NOT NULL,
            FOREIGN KEY (scan_history_id) REFERENCES scan_history(id) ON DELETE CASCADE
        )"""

    with get_connection() as connection:
        connection.execute(user_table)
        # Existing users are retained as verified during this additive migration.
        if _postgresql_requested():
            connection.execute(
                "ALTER TABLE users ADD COLUMN IF NOT EXISTS "
                "email_verified BOOLEAN NOT NULL DEFAULT TRUE"
            )
            verification_table = """CREATE TABLE IF NOT EXISTS email_verifications (
                email TEXT PRIMARY KEY,
                otp_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                attempts INTEGER NOT NULL DEFAULT 0
            )"""
        else:
            columns = {
                row["name"] for row in connection.execute("PRAGMA table_info(users)").fetchall()
            }
            if "email_verified" not in columns:
                connection.execute(
                    "ALTER TABLE users ADD COLUMN email_verified INTEGER NOT NULL DEFAULT 1"
                )
            verification_table = """CREATE TABLE IF NOT EXISTS email_verifications (
                email TEXT PRIMARY KEY,
                otp_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                attempts INTEGER NOT NULL DEFAULT 0
            )"""
        connection.execute(verification_table)
        connection.execute(history_table)
        connection.execute(results_table)
        connection.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_uq "
            "ON users (LOWER(username))"
        )
        connection.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uq "
            "ON users (LOWER(email))"
        )

    # Restrict local SQLite account data on POSIX hosts.
    if not _postgresql_requested():
        try:
            database_path().chmod(0o600)
        except OSError:
            pass
